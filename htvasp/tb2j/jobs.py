# Number pattern for the exchange.out numeric fields. Handles integers,
# decimals, trailing-dot notation ("0.") and scientific notation ("1.2e-05").
# TB2J could emit any of these after a version change, and the pair parser must
# keep matching the whole line instead of silently dropping the pair.
_NUM_PATTERN = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?"
# Matches numbers in tensor rows, including trailing-dot notation like "0.   ".
_NUM_RE = re.compile(_NUM_PATTERN)

# Line like: "   Co1   Ni1   ( -1,  -1,  -1)  4.8244   (-1.406, -1.406, -1.406)  2.435 "
# The jiso/vector/distance numeric groups share _NUM_PATTERN with _NUM_RE so
# trailing-dot / scientific-notation values match the whole line. The cell
# image R is always an integer (-?\d+).
_PAIR_RE = re.compile(
    r"^\s*(?P<i>[A-Z][a-z]?\d+)\s+(?P<j>[A-Z][a-z]?\d+)\s+"
    r"\(\s*(?P<r0>-?\d+)\s*,\s*(?P<r1>-?\d+)\s*,\s*(?P<r2>-?\d+)\s*\)\s+"
    rf"(?P<jiso>{_NUM_PATTERN})\s+"
    rf"\(\s*(?P<v0>{_NUM_PATTERN})\s*,\s*(?P<v1>{_NUM_PATTERN})\s*,\s*(?P<v2>{_NUM_PATTERN})\s*\)\s+"
    rf"(?P<dist>{_NUM_PATTERN})\s*$"
)
_PAIR_CANDIDATE_RE = re.compile(
    r"^\s*[A-Z][a-z]?\d+\s+[A-Z][a-z]?\d+\s*\("
)
_PRODUCER_RE = re.compile(r"Exchange parameters generated by TB2J\s+(?P<version>\S+)")
_J_UNIT_HEADER_RE = re.compile(r"J_iso\s*\(\s*meV\s*\)", flags=re.IGNORECASE)
_MOMENT_HEADER_RE = re.compile(r"\bw_magmom\b", flags=re.IGNORECASE)

TB2J_SCHEMA_VERSION = "emtdb-magnetic-dataset/v1"
TB2J_J_UNIT = "meV"
TB2J_MOMENT_UNIT = "mu_B"
TB2J_LENGTH_UNIT = "angstrom"
TB2J_HAMILTONIAN = "H=-sum(J_ij S_i dot S_j)"
TB2J_PAIR_COUNTING = "outgoing_per_site"
TB2J_REVERSE_PAIR_POLICY = "allow_single_outgoing_validate_reverse_if_present"


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _reverse_pair_key(pair: dict[str, Any]) -> tuple[str, str, tuple[int, int, int]]:
    return (
        str(pair["j"]),
        str(pair["i"]),
        tuple(-int(value) for value in pair["R"]),
    )


def _site_element(site: dict[str, Any]) -> str | None:
    species = site.get("species")
    if isinstance(species, list) and species and isinstance(species[0], dict):
        value = species[0].get("element") or species[0].get("label")
        if isinstance(value, str) and value.strip():
            return value.strip().split(" ", 1)[0]
    label = site.get("label")
    if isinstance(label, str) and label.strip():
        match = re.match(r"[A-Za-z]+", label.strip())
        return match.group(0) if match else None
    return None


def _moment_element(moment: dict[str, Any]) -> str | None:
    value = moment.get("element") or moment.get("atom") or moment.get("site")
    if not isinstance(value, str) or not value.strip():
        return None
    match = re.match(r"[A-Za-z]+", value.strip())
    return match.group(0) if match else None


def _validate_reverse_pairs(
    j_pairs: list[dict[str, Any]],
    j_tensors: list[list[list[float]]],
) -> dict[str, Any]:
    """Validate reciprocity only when an oriented reverse record is present.

    A native TB2J file may contain one outgoing record per site, so absence of
    a reverse record is legal.  If both records exist, scalar J values must
    agree and the full tensors must be transposes; downstream outgoing sums do
    not halve the records a second time.
    """

    indices = {
        (str(pair["i"]), str(pair["j"]), tuple(int(value) for value in pair["R"])): index
        for index, pair in enumerate(j_pairs)
    }
    reciprocal_records = 0
    for index, pair in enumerate(j_pairs):
        reverse_index = indices.get(_reverse_pair_key(pair))
        if reverse_index is None:
            continue
        reciprocal_records += 1
        reverse = j_pairs[reverse_index]
        if not math.isclose(
            float(pair["J_iso_meV"]), float(reverse["J_iso_meV"]), rel_tol=1.0e-9, abs_tol=1.0e-12
        ):
            raise ValueError(
                f"reverse exchange pair J mismatch for {pair['i']!r},{pair['j']!r},{pair['R']!r}"
            )
        tensor = j_tensors[index]
        reverse_tensor = j_tensors[reverse_index]
        if len(tensor) != 3 or len(reverse_tensor) != 3 or any(
            len(row) != 3 for row in tensor + reverse_tensor
        ):
            raise ValueError("exchange tensors must be 3x3 for reverse-pair validation")
        if any(
            not math.isclose(
                float(tensor[row][column]),
                float(reverse_tensor[column][row]),
                rel_tol=1.0e-9,
                abs_tol=1.0e-12,
            )
            for row in range(3)
            for column in range(3)
        ):
            raise ValueError(
                f"reverse exchange tensor is not the transpose for pair index {index}"
            )
    return {
        "policy": TB2J_REVERSE_PAIR_POLICY,
        "reverse_consistency_checked": True,
        "oriented_pair_records": len(j_pairs),
        "reciprocal_pair_records": reciprocal_records,
        "reciprocal_pair_groups": reciprocal_records // 2,
        "double_counting_rule": (
            "retain oriented outgoing records and sum each record for its source site; do not halve"
        ),
    }


def canonicalize_tb2j_result(
    data: dict[str, Any],
    output_path: str | Path | None = None,
    magnetic_context: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Attach the production magnetic contract before writing ``tb2j.json``.

    The raw exchange output is generated in scratch storage during a flow and
    then copied to ``tb2jflow/3-tb2j_solve``.  When that persistent copy exists,
    its path and digest are authoritative; otherwise the original source path
    is used.  No numerical exchange value is changed here.
    """

    # Keep the established jobs.py entry point while delegating the
    # dependency-free v2 implementation to magnetic_contract.py.
    return _v2_canonicalize_tb2j_result(
        data,
        output_path=output_path,
        magnetic_context=magnetic_context,
    )


def _strip_host(prev_dir: str | Path) -> Path:
    """Strip a jobflow ``host:path`` prefix from a directory reference.

    jobflow's local runner stores job ``dir_name`` values host-qualified (e.g.
    ``429pro:/nfs_ssd/tmp/SER-Co-cf44920f/3-w90_static``). Downstream jobs that
    receive ``job.output.dir_name`` must drop the ``host:`` prefix before
    touching the filesystem. Plain paths are returned unchanged.

    Args:
        prev_dir: Possibly host-qualified path.

    Returns:
        Path without any ``host:`` prefix.
    """
    s = str(prev_dir)
    head = s.split("/", 1)[0]
    if ":" in head:
        s = s.split(":", 1)[1]
    return Path(s)


def _ensure_file(prev_dir: Path, name: str) -> Path:
    """Return ``prev_dir/name``, decompressing ``name.gz`` if necessary.

    atomate2's ``BaseVaspMaker`` gzips the VASP input/output files of every
    completed job (``SETTINGS.VASP_ZIP_FILES`` = "atomate", covering e.g.
    vasprun.xml, POSCAR, OUTCAR) *before* the downstream TB2J solve job runs.
    Restore the plain file so ``Vasprun`` / TB2J's ``wann2J`` can read it.

    Args:
        prev_dir: The (host-prefix-stripped) Wannier90 output directory.
        name: File name to ensure exists uncompressed.

    Returns:
        Path to the plain file.
    """
    plain = prev_dir / name
    if plain.exists():
        return plain
    gz = prev_dir / f"{name}.gz"
    if gz.exists():
        import gzip

        with gzip.open(gz, "rb") as fin, open(plain, "wb") as fout:
            shutil.copyfileobj(fin, fout)
        log.debug(f"Decompressed {gz.name} -> {name} for TB2J solve")
    return plain


def get_efermi(prev_dir: str | Path) -> float | None:
    """Extract the Fermi energy from a VASP ``vasprun.xml``.

    Args:
        prev_dir: Directory containing the SCF + Wannier90 vasprun.xml.

    Returns:
        Fermi energy in eV, or None if it could not be read.
    """
    prev_dir = _strip_host(prev_dir)
    vasprun_path = _ensure_file(prev_dir, "vasprun.xml")
    if not vasprun_path.exists():
        log.warning(f"vasprun.xml not found in {prev_dir}")
        return None
    try:
        vasprun = Vasprun(vasprun_path, parse_dos=True, parse_potcar_file=False)
        return vasprun.efermi
    except Exception as exc:  # noqa: BLE001 - report and fall back
        log.warning(f"Failed to read efermi from {vasprun_path}: {exc}")
        return None


def run_wann2j(
    prev_dir: str | Path,
    efermi: float,
    elements: list[str],
    kmesh: tuple[int, int, int] = (9, 9, 9),
    output_path: str | Path | None = None,
) -> subprocess.CompletedProcess:
    """Run TB2J's ``python -m TB2J.scripts.wann2J``.

    Args:
        prev_dir: Directory with the Wannier90 output (wannier90.1_hr.dat, ...).
        efermi: Fermi energy in eV.
        elements: Magnetic elements (space separated for --elements).
        kmesh: Monkhorst-Pack / Gamma grid for the real-space interpolation.
        output_path: Directory where exchange.out is written (default: cwd).

    Returns:
        CompletedProcess from subprocess.run.
    """
    prev_dir = _strip_host(prev_dir).resolve()
    output_path = Path(output_path) if output_path is not None else Path.cwd()
    output_path.mkdir(parents=True, exist_ok=True)

    cmd = [
        sys.executable,
        "-m",
        "TB2J.scripts.wann2J",
        "--path",
        str(prev_dir),
        "--posfile",
        str(prev_dir / "POSCAR"),
        "--efermi",
        f"{efermi:.8f}",
        "--kmesh",
        *(str(k) for k in kmesh),
        "--elements",
        *elements,
        "--prefix_up",
        "wannier90.1",
        "--prefix_down",
        "wannier90.2",
        "--output_path",
        str(output_path),
    ]
    log.info(f"Running TB2J: {' '.join(cmd)}")
    return subprocess.run(cmd, capture_output=True, text=True)


def parse_exchange_out(path: str | Path) -> dict[str, Any]:
    """Parse a TB2J ``exchange.out`` file into structured J data.

    Args:
        path: Path to exchange.out.

    Returns:
        Dict with ``j_pairs`` (list of {i, j, R, J_iso_meV, vector, distance}),
        ``j_tensors`` (list of 3x3 meV tensors, parallel to j_pairs),
        ``atom_moments`` (per-atom wannier charge/magmom), ``cell`` and
        ``warnings`` (non-fatal messages, e.g. J_iso markers with no matching
        pair line).
    """
    source_path = Path(path).resolve()
    text = source_path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not _J_UNIT_HEADER_RE.search(text):
        raise ValueError(
            "exchange.out is missing an explicit J_iso(meV) header; refusing to assign J units"
        )
    if not _MOMENT_HEADER_RE.search(text):
        raise ValueError("exchange.out is missing the w_magmom column header")
    producer_match = _PRODUCER_RE.search(text)

    j_pairs: list[dict[str, Any]] = []
    j_tensors: list[list[list[float]]] = []
    atom_moments: list[dict[str, Any]] = []
    cell: list[list[float]] | None = None

    # Line index of the last successfully parsed pair line. A "J_iso:" marker
    # whose immediately preceding line was NOT such a pair means the pair line
    # changed format and was silently skipped - count those so the caller can
    # warn instead of losing J pairs unnoticed.
    last_pair_line: int | None = None
    dropped_jiso: int = 0

    i, n = 0, len(lines)
    while i < n:
        line = lines[i]

        if line.startswith("Cell (Angstrom):"):
            cell = [list(map(float, lines[i + 1 + k].split())) for k in range(3)]
            i += 4
            continue

        if line.startswith("Atom number") and "w_charge" in line:
            i += 1
            while i < n:
                tok = lines[i].strip()
                if not tok or tok.startswith("Total"):
                    break
                parts = tok.split()
                if len(parts) == 6:
                    atom_moments.append(
                        {
                            "atom": parts[0],
                            "xyz": [float(x) for x in parts[1:4]],
                            "w_charge": float(parts[4]),
                            "w_magmom": float(parts[5]),
                        }
                    )
                i += 1
            continue

        if line.startswith("J_iso:") and last_pair_line != i - 1:
            dropped_jiso += 1

        m = _PAIR_RE.match(line)
        if m:
            last_pair_line = i
            d = m.groupdict()
            tensor: list[list[float]] = []
            k = i + 1
            while k < n and len(tensor) < 3:
                if "[" in lines[k]:
                    nums = _NUM_RE.findall(lines[k])
                    if nums:
                        tensor.append([float(x) for x in nums])
                k += 1
            if len(tensor) != 3 or any(len(row) != 3 for row in tensor):
                raise ValueError(
                    f"exchange tensor after pair line {i + 1} must be a 3x3 matrix"
                )
            j_pairs.append(
                {
                    "i": d["i"],
                    "j": d["j"],
                    "R": [int(d["r0"]), int(d["r1"]), int(d["r2"])],
                    "J_iso_meV": float(d["jiso"]),
                    "vector": [float(d["v0"]), float(d["v1"]), float(d["v2"])],
                    "distance": float(d["dist"]),
                }
            )
            j_tensors.append(tensor)
        elif _PAIR_CANDIDATE_RE.match(line):
            raise ValueError(
                f"unparseable exchange pair line {i + 1}: {line.strip()}"
            )
        i += 1

    warnings: list[str] = []
    if dropped_jiso:
        warnings.append(
            f"{dropped_jiso} J_iso marker(s) had no matching pair line - "
            "J pair(s) were silently dropped (e.g. trailing-dot or "
            "scientific-notation numbers in exchange.out)"
        )

    reverse_audit = _validate_reverse_pairs(j_pairs, j_tensors)
    source_sha256 = _sha256_file(source_path)
    pair_keys = [
        (str(pair["i"]), str(pair["j"]), tuple(int(value) for value in pair["R"]))
        for pair in j_pairs
    ]
    if len(set(pair_keys)) != len(pair_keys):
        raise ValueError("exchange.out contains duplicate oriented exchange pair keys")
    producer_version = producer_match.group("version") if producer_match else None
    for moment in atom_moments:
        moment["unit"] = TB2J_MOMENT_UNIT
        moment["moment_unit"] = TB2J_MOMENT_UNIT

    return {
        "schema_version": TB2J_SCHEMA_VERSION,
        "exchange_out_path": source_path.as_posix(),
        "cell": cell,
        "atom_moments": atom_moments,
        "j_pairs": j_pairs,
        "j_tensors": j_tensors,
        "num_j_pairs": len(j_pairs),
        "num_atoms": len(atom_moments),
        "producer": "TB2J",
        "producer_version": producer_version,
        "units": {
            "J": TB2J_J_UNIT,
            "J_iso": TB2J_J_UNIT,
            "distance": TB2J_LENGTH_UNIT,
            "vector": TB2J_LENGTH_UNIT,
            "w_magmom": TB2J_MOMENT_UNIT,
        },
        "exchange_convention": {
            "hamiltonian": TB2J_HAMILTONIAN,
            "j_positive_is_ferromagnetic": True,
            "pair_counting": TB2J_PAIR_COUNTING,
            "spin_normalization": "unit",
            "reverse_pair_policy": TB2J_REVERSE_PAIR_POLICY,
        },
        "source": {
            "path": source_path.as_posix(),
            "format": "exchange_out",
            "sha256": source_sha256,
            "producer": "TB2J",
            "producer_version": producer_version,
        },
        "provenance": {
            "schema_version": TB2J_SCHEMA_VERSION,
            "source_format": "exchange_out",
            "source_path": source_path.as_posix(),
            "source_sha256": source_sha256,
            "producer": "TB2J",
            "producer_version": producer_version,
            "j_unit": TB2J_J_UNIT,
            "moment_unit": TB2J_MOMENT_UNIT,
            "hamiltonian": TB2J_HAMILTONIAN,
            "j_positive_is_ferromagnetic": True,
            "pair_counting_rule": TB2J_PAIR_COUNTING,
            "spin_normalization": "unit",
            "reverse_pair_policy": TB2J_REVERSE_PAIR_POLICY,
            "reverse_pair_validation": reverse_audit,
            "producer_contract": "htvasp-tb2j-production/v1",
        },
        "audit": {
            "contract_status": "raw_reader_only",
            "production_ready": False,
            "review_required": True,
            "verified_checks": [
                "native exchange.out J_iso(meV) header",
                "parallel j_pairs and j_tensors",
                "reverse pair consistency if present",
                "raw reader contract is not physical production approval",
            ],
            "reverse_pair_policy": reverse_audit,
        },
        "warnings": warnings,
    }


@job
def tb2j_solve(
    prev_dir: str | Path,
    elements: list[str],
    kmesh: tuple[int, int, int] = (9, 9, 9),
    num_wann: int | None = None,
    magnetic_context: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Solve for exchange parameters J using TB2J (wann2J).

    Reads the Fermi energy from ``prev_dir``/vasprun.xml, runs
    ``python -m TB2J.scripts.wann2J`` with the collinear Wannier90 output, and
    parses the resulting ``exchange.out`` into structured J data.

    Args:
        prev_dir: Directory with the SCF + Wannier90 VASP output.
        elements: Magnetic elements (passed to TB2J --elements).
        kmesh: kmesh for the TB2J real-space interpolation.
        num_wann: Number of Wannier orbitals (for provenance; optional).

    Returns:
        Dict with exchange_out_path, efermi, num_atoms, structure, elements,
        kmesh, num_wann, j_pairs, j_tensors, atom_moments and warnings.
    """
    prev_dir = _strip_host(prev_dir)
    warnings: list[str] = []

    efermi = get_efermi(prev_dir)
    if efermi is None:
        raise RuntimeError(f"Could not extract Fermi energy from {prev_dir}")

    poscar_path = _ensure_file(prev_dir, "POSCAR")
    if not poscar_path.exists():
        raise FileNotFoundError(f"POSCAR not found in {prev_dir}")
    structure = Structure.from_file(poscar_path)
    num_atoms = len(structure)

    result = run_wann2j(prev_dir, efermi, elements, kmesh=kmesh, output_path=Path.cwd())
    if result.returncode != 0:
        raise RuntimeError(
            f"TB2J wann2J failed (returncode={result.returncode}): "
            f"{result.stderr.strip()}\nstdout:\n{result.stdout.strip()}"
        )

    exchange_out_path = Path.cwd() / "exchange.out"
    if not exchange_out_path.exists():
        raise RuntimeError(f"TB2J finished but no exchange.out in {Path.cwd()}")

    parsed = parse_exchange_out(exchange_out_path)
    warnings.extend(parsed.get("warnings", []))
    if parsed["num_j_pairs"] == 0:
        warnings.append("No J pairs parsed from exchange.out")

    if num_atoms is None and parsed["atom_moments"]:
        num_atoms = len(parsed["atom_moments"])

    canonical = canonicalize_tb2j_result(
        {
            "exchange_out_path": parsed["exchange_out_path"],
            "efermi": efermi,
            "num_atoms": num_atoms,
            "structure": structure.as_dict(),
            "elements": list(elements),
            "kmesh": list(kmesh),
            "num_wann": num_wann,
            "j_pairs": parsed["j_pairs"],
            "j_tensors": parsed["j_tensors"],
            "atom_moments": parsed["atom_moments"],
            "num_j_pairs": parsed["num_j_pairs"],
            "warnings": warnings,
        },
        magnetic_context=magnetic_context,
    )
    return canonical
