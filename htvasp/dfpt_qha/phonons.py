"""Ordering-safe phonopy construction for DFPT force constants.

The hazard this module exists to close
--------------------------------------
A DFPT force-constant matrix is indexed by the atom order of the POSCAR VASP
read.  phonopy indexes its own supercell in a DIFFERENT order.  For the 2-atom
B2 cell the two disagree on 8 of 16 sites::

    pymatgen / VASP POSCAR   Al(0,0,0)  Al(0,0,1/2)  Al(0,1/2,0)  ...
    phonopy supercell        Al(0,0,0)  Al(1/2,0,0)  Al(0,1/2,0)  ...

Same atoms, same crystal, different indices.  Attaching a force-constant matrix
across the two orderings still produces a matrix that is nonzero, symmetric and
gives plausible-looking frequencies -- it is simply the wrong assignment.  The
Gamma-point acoustic sum rule does not catch it either: a consistent permutation
of both indices is a similarity transform, so the Gamma frequencies are
unchanged.  Only the finite-q frequencies move.

The fix is to remove the ambiguity rather than reconcile it: the supercell the
DFPT job runs on is generated BY phonopy (``Phonopy.supercell``), so VASP's
POSCAR order and phonopy's index order are the same list by construction.
``supercell_structure`` is the single place that mapping is made, and the
fingerprint it returns is what a later consumer asserts against.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any

import numpy as np
from phonopy import Phonopy
from phonopy.structure.atoms import PhonopyAtoms
from pymatgen.core import Structure


def as_structure(value: Any) -> Structure:
    """Accept a ``Structure`` or its serialized dict.

    jobflow stores a job's output as JSON and monty's decoder rebuilds the
    objects it recognises, so a value written as ``structure.as_dict()`` comes
    back as a live ``Structure``.  Which form arrives depends on the runner, not
    on the code, so every job boundary accepts both rather than assuming.
    """

    if isinstance(value, Structure):
        return value
    return Structure.from_dict(value)


def phonopy_for(cell: Structure, supercell_matrix: Any) -> Phonopy:
    """A phonopy object for the primitive cell, with no force constants set.

    ``primitive_matrix="auto"`` and the default symmetry settings match what the
    verified Stage 0B analysis used, so frequencies are comparable with it.
    """

    atoms = PhonopyAtoms(
        symbols=[str(site.specie) for site in cell],
        scaled_positions=[site.frac_coords for site in cell],
        cell=cell.lattice.matrix,
    )
    return Phonopy(
        atoms,
        supercell_matrix=np.array(supercell_matrix, dtype=float),
        primitive_matrix="auto",
        symprec=1e-3,
    )


def supercell_structure(cell: Structure, supercell_matrix: Any) -> Structure:
    """The supercell the DFPT job must run on: phonopy's own, as pymatgen.

    Do NOT replace this with ``cell.make_supercell(matrix)``.  pymatgen's
    ordering equals the hand-built POSCAR ordering, which is NOT phonopy's, and
    using it would silently mis-index every force constant returned from the
    calculation.
    """

    supercell = phonopy_for(cell, supercell_matrix).supercell
    return Structure(
        np.array(supercell.cell),
        list(supercell.symbols),
        [np.array(p) for p in supercell.scaled_positions],
        coords_are_cartesian=False,
    )


def ordering_fingerprint(structure: Structure) -> str:
    """Order-sensitive identity of a cell: lattice, species and coordinates.

    Two structures with the same atoms in a different order hash differently,
    which is exactly the property a force-constant consumer needs to check.
    """

    payload = {
        "lattice": [[round(float(x), 8) for x in row] for row in structure.lattice.matrix],
        "species": [str(site.specie) for site in structure],
        "coords": [[round(float(x), 8) for x in site.frac_coords] for site in structure],
    }
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def assert_same_ordering(expected: Structure, actual: Structure) -> None:
    """Fail loudly if a force-constant matrix is about to be mis-indexed."""

    if ordering_fingerprint(expected) != ordering_fingerprint(actual):
        raise ValueError(
            "phonopy supercell ordering does not match the cell the force "
            "constants were computed on; attaching them would mis-index every "
            "element.  The DFPT job must run on phonopy's own supercell "
            "(see supercell_structure), not on a hand-built or "
            "pymatgen.make_supercell cell."
        )


__all__ = [
    "as_structure",
    "assert_same_ordering",
    "ordering_fingerprint",
    "phonopy_for",
    "supercell_structure",
]
