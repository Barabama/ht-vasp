"""Dynamic sub-flows must be resumable.

A DFPT endpoint expands into a ``Response(replace=Flow(...))`` sub-flow of one
VASP job per volume.  On resume the parent job is re-executed (its stored
output is None when the sub-flow did not finish), which rebuilds the sub-flow
with brand-new job uuids.  Forcing ``resume=False`` on that sub-flow re-ran
every volume whose TaskDoc was already in the store -- hours of VASP per
interrupted endpoint.
"""

from __future__ import annotations

from jobflow import Flow, JobStore, Response, job
from maggma.stores import MemoryStore

import shutil

from htvasp.utils.local import run_locally_custom
from htvasp.workflows.base import Worker

EXECUTIONS = {"first": 0, "second": 0, "fail": True}


@job
def first():
    EXECUTIONS["first"] += 1
    return {"value": 1}


@job
def second(previous):
    EXECUTIONS["second"] += 1
    if EXECUTIONS["fail"]:
        raise RuntimeError("simulated interruption")
    return {"value": previous["value"] + 1}


@job
def parent():
    a = first()
    b = second(a.output)
    return Response(replace=Flow([a, b], output=b.output, name="sub"))


class _Probe(Worker):
    """A Worker whose flow is a single job, so resume is easy to observe."""

    def __init__(self):
        super().__init__(worker_name="probe")

    def _make_flow(self, structure, prev_dir=None):
        return Flow([first()], name="probe")


def _store() -> JobStore:
    store = MemoryStore()
    store.connect()
    return JobStore(store)


def test_dynamic_sub_flow_reuses_completed_jobs_on_resume(tmp_path):
    EXECUTIONS.update({"first": 0, "second": 0, "fail": True})
    store = _store()

    run_locally_custom(parent(), store=store, root_dir=tmp_path, resume=True)
    assert EXECUTIONS["first"] == 1
    assert EXECUTIONS["second"] == 1

    # the interruption is over; resuming must not re-run the completed job
    EXECUTIONS["fail"] = False
    run_locally_custom(parent(), store=store, root_dir=tmp_path, resume=True)
    assert EXECUTIONS["first"] == 1, "completed sub-flow job was executed again"
    assert EXECUTIONS["second"] == 2


# --------------------------------------------------------------------------
# flow-directory naming and the explicit resume source
# --------------------------------------------------------------------------

def _orphan_scratch(worker, name, flow_root, store_dir, flow_dir_name, legacy_suffix=None):
    """Run once, then put the store back where a SIGTERM would have left it.

    A run that finishes normally moves ``flow_dir`` into ``store_dir`` in the
    ``finally`` block.  A run killed at its Slurm time limit gets SIGTERM and
    skips that block, so the store stays in the scratch directory and
    ``store_dir`` is never created.  Moving it back reproduces that state
    without needing to kill a process.
    """
    worker.run_flow(name=name, structure=None, flow_dir=flow_root,
                    store_dir=store_dir, resume=False,
                    flow_dir_name=flow_dir_name)
    suffix = legacy_suffix or flow_dir_name
    target = flow_root / f"{name}-{suffix}"
    target.mkdir(parents=True, exist_ok=True)
    shutil.copytree(store_dir, target, dirs_exist_ok=True)
    shutil.rmtree(store_dir)
    return target


def test_a_killed_run_is_found_again_by_its_flow_dir_name(tmp_path):
    """A SIGTERM leaves no store_dir, so the scratch directory must be findable.

    ``Flow.uuid`` is regenerated by ``suid()`` on every invocation, so the
    default ``<name>-<uuid8>`` directory of a killed run is orphaned.  Naming it
    after something stable -- a run id -- makes the next resume find it in
    place, without the ``finally`` block that a SIGTERM skips.
    """
    flow_root = tmp_path / "scratch"
    store_dir = tmp_path / "store"
    EXECUTIONS.update({"first": 0, "second": 0, "fail": False})
    scratch = _orphan_scratch(_Probe(), "endpoint", flow_root, store_dir, "run-abc")
    assert (scratch / "store.json").is_file()
    assert not store_dir.exists()

    EXECUTIONS.update({"first": 0, "second": 0, "fail": False})
    _Probe().run_flow(name="endpoint", structure=None, flow_dir=flow_root,
                      store_dir=store_dir, resume=True, flow_dir_name="run-abc")
    # Resumed in place: the completed job was not executed a second time.
    assert EXECUTIONS["first"] == 0


def test_an_explicit_resume_from_directory_is_used_when_the_named_one_is_absent(tmp_path):
    """A run started before the naming change sits under a uuid directory."""
    flow_root = tmp_path / "scratch"
    store_dir = tmp_path / "store"
    EXECUTIONS.update({"first": 0, "second": 0, "fail": False})
    legacy = _orphan_scratch(_Probe(), "endpoint", flow_root, store_dir,
                             "run-xyz", legacy_suffix="1a2b3c4d")
    assert (legacy / "store.json").is_file()

    EXECUTIONS.update({"first": 0, "second": 0, "fail": False})
    _Probe().run_flow(name="endpoint", structure=None, flow_dir=flow_root,
                      store_dir=store_dir, resume=True,
                      flow_dir_name="run-new", resume_from=legacy)
    assert EXECUTIONS["first"] == 0
    # The flow ran to completion, so its directory was archived to store_dir.
    assert (store_dir / "store.json").is_file()


def test_resume_from_without_a_store_is_refused(tmp_path):
    import pytest

    from htvasp.workflows.base import Worker

    class _Probe(Worker):
        def __init__(self):
            super().__init__(worker_name="probe")

        def _make_flow(self, structure, prev_dir=None):
            return Flow([first()], name="probe")

    empty = tmp_path / "empty"
    empty.mkdir()
    with pytest.raises(FileNotFoundError, match="no store.json"):
        _Probe().run_flow(name="endpoint", structure=None, flow_dir=tmp_path / "s",
                          store_dir=tmp_path / "d", resume=True,
                          resume_from=empty)


